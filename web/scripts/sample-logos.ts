/**
 * ADR-0016 D6: renders each sample company's mark (lib/sample/logos.ts) to a
 * 256 px PNG on a white tile, for the client deck. Google's conversion of SVG
 * images in a .pptx isn't reliable, so the deck embeds these instead.
 *
 *   npm run sample-logos     rewrites src/server/deck/logos.generated.ts
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import sharp from "sharp";
import { logoSvg } from "../src/lib/sample/logos";
import { SampleSeller } from "../src/lib/schema/workspace";

async function main() {
  const lines: string[] = [];
  for (const seller of SampleSeller.options) {
    // The mark is 40 units wide; a 4-unit margin keeps it off the tile's edge.
    const svg = logoSvg(seller).replace('viewBox="0 0 40 40" width="40" height="40"', 'viewBox="-4 -4 48 48" width="256" height="256"');
    const png = await sharp(Buffer.from(svg)).flatten({ background: "#FFFFFF" }).png().toBuffer();
    lines.push(`  ${seller}: "image/png;base64,${png.toString("base64")}",`);
    console.log(`${seller}: ${png.length} bytes`);
  }
  const out = resolve(__dirname, "../src/server/deck/logos.generated.ts");
  writeFileSync(
    out,
    [
      "// Generated by scripts/sample-logos.ts from lib/sample/logos.ts. Do not edit.",
      'import type { SampleSeller } from "@/lib/schema";',
      "",
      "export const LOGO_PNG: Record<SampleSeller, string> = {",
      ...lines,
      "};",
      "",
    ].join("\n"),
  );
  console.log(`wrote ${out}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
